export function normalizeTerm(s: string) {
  return s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}
export function matchesTerm(id: string, term: string) {
  const b = boneById[id];
  return [b.name, ...b.aliases].some(
    (n) => normalizeTerm(n) === normalizeTerm(term),
  );
}
